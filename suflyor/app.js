const HALLU = [/субтитр/i, /продолжение следует/i, /спасибо за просмотр/i, /dimatorzok/i, /редактор субтитров/i, /подписывайтесь на канал/i, /корректор/i, /^[\s\p{P}\p{S}]*$/u];
function cleanWhisper(t){
  t = String(t||'').replace(/\s+/g,' ').trim();
  if(!t || HALLU.some(r=>r.test(t))) return '';
  // повторяющиеся фразы — частая петля декодера
  t = t.replace(/(^|\s)([^.!?]{4,60}?[.!?]?)(?:\s+\2){2,}/giu, '$1$2');
  return t;
}
async function decodeTo16k(blob){
  const buf = await blob.arrayBuffer();
  const AC = window.AudioContext||window.webkitAudioContext; const ac = new AC();
  let decoded; try{ decoded = await ac.decodeAudioData(buf); } finally { try{ ac.close(); }catch(_){} }
  if(decoded.duration > 90*60) throw new Error('Запись длиннее 90 минут. Разбейте её на части.');
  const len = Math.ceil(decoded.duration*16000);
  const off = new OfflineAudioContext(1, len, 16000);
  const src = off.createBufferSource(); src.buffer = decoded; src.connect(off.destination); src.start();
  const r = await off.startRendering();
  return r.getChannelData(0);
}
