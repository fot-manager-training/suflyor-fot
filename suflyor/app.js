function maskPII(text){
  return String(text??'')
    .replace(/[\w.+-]+@[\w-]+\.[\w.-]+/g,'[email]')
    .replace(/(?:\+7|(?<![\d])8)[\s(-]*\d{3}[\s)-]*\d{3}[\s-]*\d{2}[\s-]*\d{2}(?!\d)/g,'[телефон]')
    .replace(/(?<!\d)(?:\d[ -]?){15,18}\d(?!\d)/g,'[номер]')
    .replace(/(?:[А-ЯЁ][а-яё]+\s+)?[А-ЯЁ][а-яё]+(?:ович|евич|ьич|овна|евна|ична)(?![а-яё])/g,'[имя]')
    .replace(/(кабинет[а-яё]*|каб\.?)\s*№?\s*\d+[а-яё]?/gi,'$1 [№]');
}
function maskObject(value){
  if(typeof value==='string')return maskPII(value);
  if(Array.isArray(value))return value.map(maskObject);
  if(value&&typeof value==='object')return Object.fromEntries(Object.entries(value).map(([key,item])=>[key,maskObject(item)]));
  return value;
}
