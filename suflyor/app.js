function mergeKnowledgeText(current,documents,target){
  let text=current||'';
  for(const doc of documents||[]){
    if(doc.target!==target||!doc.text||!doc.id)continue;
    const marker='=== ИСТОЧНИК: '+doc.id+' ===';
    if(!text.includes(marker))text+='\n\n'+marker+'\n'+doc.title+'\n'+doc.text;
  }
  return text;
}
function replaceKnowledgeBase(current,target,bundle){
  const base=bundle.documents.filter(d=>d.target===target).map(d=>d.text).join('\n\n');
  if(!base)return current;
  let extra=String(current||'');
  // Remove the exact previous managed content; custom additions remain separate.
  for(const known of [Knowledge.previousDefaults?.[target],Knowledge.defaults[target],bundle.legacy?.bases?.[target],base]){
    if(known&&extra.startsWith(known))extra=extra.slice(known.length);
  }
  for(const doc of [...(bundle.legacy?.documents||[]),...bundle.documents]){
    if(doc.target!==target)continue;
    const block='=== ИСТОЧНИК: '+doc.id+' ===\n'+doc.title+'\n'+doc.text;
    extra=extra.replace(block,'');
  }
  extra=extra.trim();
  return base+(extra?'\n\n'+extra:'');
}
function applyKnowledgeBundle(bundle){
  if(!bundle||!Array.isArray(bundle.documents))return false;
  if(bundle.schemaVersion===2){
    // Both authoritative documents are required before replacing a stored base.
    if(!['zp','sp'].every(target=>bundle.documents.some(d=>d.target===target&&typeof d.text==='string'&&d.text.trim())))return false;
    const before={zp:App.kbZp,sp:App.kbSp,bundleVersion:Knowledge.version};
    const next={zp:replaceKnowledgeBase(App.kbZp,'zp',bundle),sp:replaceKnowledgeBase(App.kbSp,'sp',bundle)};
    if((before.zp!==next.zp||before.sp!==next.sp)&&Knowledge.version!==bundle.version){
      Knowledge.pendingBackup={...before,replacedAt:Date.now(),replacedBy:bundle.version};
    }
    App.kbZp=next.zp;App.kbSp=next.sp;
    Knowledge.defaults={zp:bundle.documents.filter(d=>d.target==='zp').map(d=>d.text).join('\n\n'),sp:bundle.documents.filter(d=>d.target==='sp').map(d=>d.text).join('\n\n')};
  }else{
    Knowledge.defaults.zp=mergeKnowledgeText(KB_ZP_DEFAULT,bundle.documents,'zp');
    Knowledge.defaults.sp=mergeKnowledgeText(KB_SPEECH_DEFAULT,bundle.documents,'sp');
    App.kbZp=mergeKnowledgeText(App.kbZp,bundle.documents,'zp');App.kbSp=mergeKnowledgeText(App.kbSp,bundle.documents,'sp');
  }
  Knowledge.version=bundle.version||'';Knowledge.sources=bundle.documents.map(d=>d.title);
  Knowledge.previousDefaults=Knowledge.defaults;
  return true;
}
